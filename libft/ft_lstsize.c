#include "../minishell.h"

int	ft_lstsize(t_list *lst)
{
	int	count;

	count = 0;
	if (lst == NULL)
	{
		return (0);
	}
	while (lst != NULL)
	{
		lst = lst->next;
		count++;
	}
	return (count);
}
